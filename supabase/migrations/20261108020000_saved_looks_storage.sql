-- BarberPro AI: Save Look (PRD FR-13, FR-15, FR-16) for staff-run consultations.
--
-- ADDITIVE ONLY. Creates the private `images` storage bucket (or verifies an
-- existing one is private), storage policies, the `saved_looks` table and
-- functions to create and delete looks. No existing row is changed.
--
-- Ownership model: looks belong to a BARBERSHOP (the customer is identified by
-- a staff-entered label, not an account). Any member of that shop may view or
-- delete them; nobody else can, including in storage.
--
-- Object paths: images/{barbershop_id}/{look_id}/original.{ext}
--                images/{barbershop_id}/{look_id}/preview.{ext}
--
-- Retention: looks expire 90 days after saving (DRAFT default, pending
-- product/legal approval). Expired looks are hidden and purged by the app.
--
-- Rollback (manual, after review; deletes saved looks; remove the storage
-- objects first through the Storage API):
--   drop function public.delete_saved_look(uuid);
--   drop function public.create_saved_look(uuid, uuid, uuid, text, text, text, text, text);
--   drop policy images_select_member on storage.objects;  (and _insert_, _delete_)
--   drop function public.can_access_look_object(text);
--   drop table public.saved_looks;

-- ---------------------------------------------------------------------------
-- 1. Private bucket. Never flips an existing bucket's settings; refuses to
--    continue if a bucket named `images` already exists and is public.
-- ---------------------------------------------------------------------------
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('images', 'images', false, 8388608, array['image/jpeg', 'image/png', 'image/webp'])
on conflict (id) do nothing;

do $$
begin
  if exists (select 1 from storage.buckets where id = 'images' and public) then
    raise exception 'storage bucket "images" exists and is PUBLIC; it must be private for customer photos';
  end if;
end;
$$;

-- ---------------------------------------------------------------------------
-- 2. Storage policies: only members of the shop named by the first path
--    segment may read, upload or delete. No UPDATE policy: objects are never
--    overwritten in place.
-- ---------------------------------------------------------------------------
create function public.can_access_look_object(p_name text)
returns boolean
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_folder text := split_part(p_name, '/', 1);
begin
  -- Validate before casting so a malformed path is denied, not an error.
  if v_folder !~ '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$' then
    return false;
  end if;
  return public.is_member(v_folder::uuid);
end;
$$;

revoke all on function public.can_access_look_object(text) from public, anon;
grant execute on function public.can_access_look_object(text) to authenticated;

create policy images_select_member on storage.objects
  for select to authenticated
  using (bucket_id = 'images' and public.can_access_look_object(name));

create policy images_insert_member on storage.objects
  for insert to authenticated
  with check (bucket_id = 'images' and public.can_access_look_object(name));

create policy images_delete_member on storage.objects
  for delete to authenticated
  using (bucket_id = 'images' and public.can_access_look_object(name));

-- ---------------------------------------------------------------------------
-- 3. saved_looks
-- ---------------------------------------------------------------------------
create table public.saved_looks (
  -- Generated by the server before upload, so object paths are known up front.
  id                  uuid primary key,
  barbershop_id       uuid not null references public.barbershops (id) on delete cascade,
  created_by          uuid references auth.users (id) on delete set null,
  -- The preview this look came from; one saved look per generated preview.
  tryon_job_id        uuid references public.ai_generation_jobs (id) on delete set null,
  -- Revoking/deleting the storage consent removes the look with it.
  storage_consent_id  uuid not null references public.photo_consents (id) on delete cascade,
  customer_label      text not null
                      constraint saved_looks_customer_label_length check (char_length(btrim(customer_label)) between 1 and 100),
  title               text
                      constraint saved_looks_title_length check (title is null or char_length(btrim(title)) between 1 and 100),
  style_id            text not null
                      constraint saved_looks_style_id_format check (style_id ~ '^[a-z0-9-]{1,64}$'),
  original_path       text not null,
  preview_path        text not null,
  favorite            boolean not null default false,
  created_at          timestamptz not null default now(),
  delete_after        timestamptz not null,

  constraint saved_looks_tryon_job_key unique (tryon_job_id),
  constraint saved_looks_paths_in_folder check (
    original_path like barbershop_id::text || '/' || id::text || '/original.%'
    and preview_path like barbershop_id::text || '/' || id::text || '/preview.%'
  ),
  constraint saved_looks_delete_after_future check (delete_after > created_at)
);

create index saved_looks_shop_created_idx on public.saved_looks (barbershop_id, created_at desc);
create index saved_looks_delete_after_idx on public.saved_looks (barbershop_id, delete_after);
create index saved_looks_consent_idx on public.saved_looks (storage_consent_id);
create index saved_looks_created_by_idx on public.saved_looks (created_by);

revoke all on table public.saved_looks from anon, authenticated;
grant select on table public.saved_looks to authenticated;

alter table public.saved_looks enable row level security;
alter table public.saved_looks force row level security;

create policy saved_looks_select_member on public.saved_looks
  for select to authenticated
  using (public.is_member(barbershop_id));

-- ---------------------------------------------------------------------------
-- 4. create_saved_look: records the storage consent and the look together.
-- The style comes from the server-recorded try-on job, never from the client.
-- Idempotent per try-on job.
-- ---------------------------------------------------------------------------
create function public.create_saved_look(
  p_look_id         uuid,
  p_barbershop_id   uuid,
  p_tryon_job_id    uuid,
  p_customer_label  text,
  p_title           text,
  p_original_path   text,
  p_preview_path    text,
  p_notice_version  text
)
returns jsonb
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  c_retention   constant interval := interval '90 days';
  v_user_id     uuid := auth.uid();
  v_style_id    text;
  v_existing    uuid;
  v_consent_id  uuid;
  v_prefix      text := p_barbershop_id::text || '/' || p_look_id::text || '/';
begin
  if v_user_id is null then
    raise exception 'authentication required' using errcode = '28000';
  end if;
  if not public.is_member(p_barbershop_id) then
    raise exception 'not a member of this barbershop' using errcode = '42501';
  end if;
  if p_notice_version is null or char_length(p_notice_version) not between 1 and 64 then
    return jsonb_build_object('ok', false, 'reason', 'consent_required');
  end if;
  if left(p_original_path, char_length(v_prefix)) <> v_prefix or left(p_preview_path, char_length(v_prefix)) <> v_prefix then
    raise exception 'invalid object path' using errcode = '22023';
  end if;

  perform pg_advisory_xact_lock(hashtextextended(p_tryon_job_id::text, 2));

  -- Only a successful preview generated by this user, for this shop, can be saved.
  select style_id into v_style_id
  from public.ai_generation_jobs
  where id = p_tryon_job_id
    and user_id = v_user_id
    and barbershop_id = p_barbershop_id
    and feature = 'tryon_preview'
    and status = 'succeeded';
  if not found then
    return jsonb_build_object('ok', false, 'reason', 'invalid_job');
  end if;

  select id into v_existing from public.saved_looks where tryon_job_id = p_tryon_job_id;
  if found then
    return jsonb_build_object('ok', true, 'lookId', v_existing, 'duplicate', true);
  end if;

  insert into public.photo_consents (barbershop_id, recorded_by, purpose, notice_version)
  values (p_barbershop_id, v_user_id, 'look_storage', p_notice_version)
  returning id into v_consent_id;

  insert into public.saved_looks (
    id, barbershop_id, created_by, tryon_job_id, storage_consent_id,
    customer_label, title, style_id, original_path, preview_path, delete_after
  )
  values (
    p_look_id, p_barbershop_id, v_user_id, p_tryon_job_id, v_consent_id,
    btrim(p_customer_label), nullif(btrim(coalesce(p_title, '')), ''), v_style_id,
    p_original_path, p_preview_path, now() + c_retention
  );

  return jsonb_build_object('ok', true, 'lookId', p_look_id, 'duplicate', false);
end;
$$;

-- ---------------------------------------------------------------------------
-- 5. delete_saved_look: call AFTER removing the storage objects. Marks the
-- storage consent revoked (kept as audit history) and deletes the record.
-- ---------------------------------------------------------------------------
create function public.delete_saved_look(p_look_id uuid)
returns boolean
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v_look public.saved_looks;
begin
  if auth.uid() is null then
    raise exception 'authentication required' using errcode = '28000';
  end if;

  select * into v_look from public.saved_looks where id = p_look_id;
  if not found or not public.is_member(v_look.barbershop_id) then
    return false; -- non-disclosing: same answer for "missing" and "not yours"
  end if;

  update public.photo_consents set revoked_at = now()
  where id = v_look.storage_consent_id and revoked_at is null;

  delete from public.saved_looks where id = p_look_id;
  return true;
end;
$$;

revoke all on function public.create_saved_look(uuid, uuid, uuid, text, text, text, text, text) from public, anon;
revoke all on function public.delete_saved_look(uuid) from public, anon;
grant execute on function public.create_saved_look(uuid, uuid, uuid, text, text, text, text, text) to authenticated;
grant execute on function public.delete_saved_look(uuid) to authenticated;
